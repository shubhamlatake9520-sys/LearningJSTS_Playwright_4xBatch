//Literals Defination 
//Literals are fixed values that you write directly into your code. They represent data in a program and can be of various types, such as numbers, strings, booleans, arrays, objects, etc.

//Types of Literals in JavaScript:

// Integer Literals: Whole numbers without decimal points. Example: 42, -7, 0

let decimal = 42; // Integer literal
let negative = -7; // Integer literal
let zero = 0; // Integer literal

let binary = 0b1010; // Binary literal for 10
console.log(binary);
let octal = 0o12; // Octal literal for 10
console.log(octal);
let hexadecimal = 0xA; // Hexadecimal literal for 10    
console.log(hexadecimal);

//floating-point Literals: Numbers with decimal points. Example: 3.14, -0.001

let float1 = 3.14; // Floating-point literal
let float2 = -0.001; // Floating-point literal

let exp1 = 1.5e3; // Exponential notation for 1500
let exp2 = 2.5e-3; // Exponential notation for 0.0025
console.log(float1);
console.log(float2);
console.log(exp1);
console.log(exp2);

